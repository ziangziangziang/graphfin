#!/usr/bin/env python3
"""Render a Phase 0 baseline JSON result as a human-readable markdown report.

Usage:
    python3 report.py results/baseline.json [-o results/BASELINE.md]
"""

import argparse
import json
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))


def g(d, *path, **kw):
    """Safe nested get with a default."""
    default = kw.get("default")
    cur = d
    for p in path:
        if not isinstance(cur, dict) or p not in cur:
            return default
        cur = cur[p]
    return cur if cur is not None else default


def fmt(v, unit="", nd=2):
    if v is None:
        return "-"
    if isinstance(v, float):
        return ("%%.%df%%s" % nd) % (v, unit)
    if isinstance(v, int):
        if abs(v) >= 1000000:
            return "%.1fM%s" % (v / 1000000.0, unit)
        if abs(v) >= 1000:
            return "%.1fk%s" % (v / 1000.0, unit)
        return "%d%s" % (v, unit)
    return str(v)


def kb_to_human(kb):
    if kb is None:
        return "-"
    for unit, div in (("GiB", 1024.0 * 1024), ("MiB", 1024.0), ("KiB", 1.0)):
        if kb >= div:
            return "%.1f %s" % (kb / div, unit)
    return "%d KiB" % kb


def bytes_to_human(b):
    if b is None:
        return "-"
    for unit, div in (("GiB", 1024.0 ** 3), ("MiB", 1024.0 ** 2), ("KiB", 1024.0)):
        if b >= div:
            return "%.2f %s" % (b / div, unit)
    return "%d B" % b


def err(x):
    """Return the error string of a phase dict, if any."""
    if not isinstance(x, dict):
        return None
    return x.get("error")


def _summary_from_seconds(values):
    """Summarise a raw list of per-operation seconds (used by failure paths)."""
    if not values:
        return {"n": 0}
    ms = sorted(v * 1000.0 for v in values)

    def pct(p):
        if len(ms) == 1:
            return ms[0]
        k = (len(ms) - 1) * (p / 100.0)
        lo = int(k)
        hi = min(lo + 1, len(ms) - 1)
        return ms[lo] + (ms[hi] - ms[lo]) * (k - lo)

    return {"n": len(ms), "p50_ms": pct(50), "p95_ms": pct(95),
            "p99_ms": pct(99), "max_ms": ms[-1], "min_ms": ms[0]}


def render(doc):
    out = []
    a = out.append
    env = doc.get("env", {})
    cfg = doc.get("config", {})
    runs = doc.get("runs", {})

    a("# Phase 0 Baseline Benchmark Results")
    a("")
    a("Generated by `benchmark/scaling/report.py` from `%s`."
      % os.path.basename(doc.get("_source", "baseline.json")))
    a("")
    a("- Bench harness version: `%s`" % doc.get("phase0_bench_version", "?"))
    a("- Started: `%s`" % doc.get("started_at_utc", "?"))
    a("- Finished: `%s`" % doc.get("finished_at_utc", "?"))
    a("")

    # ---- environment ----
    a("## 1. Environment")
    a("")
    a("These numbers are only meaningful together with this environment.")
    a("")
    a("| Item | Value |")
    a("|---|---|")
    a("| Source commit | `%s` |" % (g(env, "source", "git_commit", default="?") or "?"))
    a("| Arch | %s |" % g(env, "host", "arch", default="?"))
    a("| OS | %s |" % g(env, "host", "os_release", default="?"))
    a("| Kernel | %s |" % g(env, "host", "kernel", default="?"))
    a("| CPU | %s |" % g(env, "cpu", "model", default="?"))
    a("| CPU count / affinity | %s / %s |"
      % (g(env, "cpu", "count", default="?"), g(env, "cpu", "affinity", default="?")))
    a("| MemTotal | %s |" % g(env, "memory", "mem_total_kb", default="?"))
    a("| cgroup memory limit | %s |" % g(env, "memory", "cgroup_limit_bytes", default="?"))
    a("| cgroup cpu limit | %s |" % g(env, "limits", "cgroup_cpu_max", default="?"))
    a("| cgroup pids limit | %s |" % g(env, "limits", "cgroup_pids_max", default="?"))
    a("| nofile soft/hard | %s / %s |"
      % (g(env, "limits", "nofile_soft", default="?"), g(env, "limits", "nofile_hard", default="?")))
    a("| vm.max_map_count | %s |" % g(env, "limits", "max_map_count", default="?"))
    a("| kernel.threads-max | %s |" % g(env, "limits", "threads_max", default="?"))
    a("| Data dir filesystem | %s |" % g(env, "storage", "data_dir_fstype", default="?"))
    a("| Container image id | `%s` |" % (g(env, "container", "image_id", default="") or "not recorded"))
    a("| Python | %s |" % g(env, "python", "version", default="?"))
    a("")
    a("Benchmark configuration: **max_size_GB=%s**, repeated queries=%s, "
      "throughput=%ss, threads=%s, phases=`%s`."
      % (cfg.get("max_size_gb"), cfg.get("repeated_queries"),
         cfg.get("throughput_seconds"), cfg.get("throughput_threads"),
         ",".join(cfg.get("phases", []))))
    a("")

    # ---- headline ----
    a("## 2. Headline scaling table")
    a("")
    a("`Effective graphs` differs from `Graphs` when graph creation stopped "
      "early: the remaining phases then ran against the smaller, achievable "
      "graph count.")
    a("")
    a("| Graphs | Effective graphs | Startup (s) | Restart w/ N graphs (s) | Shutdown (s) | RSS | VmSize | Threads | FDs | Mappings | Disk/graph |")
    a("|---|---|---|---|---|---|---|---|---|---|---|")
    for n in sorted(runs, key=lambda x: int(x)):
        r = runs[n]
        eff = g(r, "create", "graphs_present_at_failure", default=int(n))
        a("| %s | %s | %s | %s | %s | %s | %s | %s | %s | %s | %s |" % (
            n,
            eff,
            fmt(g(r, "startup", "seconds")),
            fmt(g(r, "restart", "seconds")),
            fmt(g(r, "shutdown", "seconds", default=g(r, "final_shutdown", "seconds"))),
            kb_to_human(g(r, "steady_metrics", "rss_kb")),
            kb_to_human(g(r, "steady_metrics", "vmsize_kb")),
            fmt(g(r, "steady_metrics", "threads")),
            fmt(g(r, "steady_metrics", "fds")),
            fmt(g(r, "steady_metrics", "maps")),
            bytes_to_human(g(r, "storage", "per_graph_bytes")),
        ))
    a("")
    a("`Restart w/ N graphs` is the key number: the server is stopped and started "
      "again with N graphs already on disk, so it isolates the cost of "
      "`GraphManager::ReloadFromDisk` (src/db/graph_manager.cpp:257-284).")
    a("")

    # ---- lifecycle latency ----
    a("## 3. Graph lifecycle latency")
    a("")
    a("| Graphs | Create p50 (ms) | Create p95 (ms) | Create max (ms) | Create total (s) | Delete p50 (ms) | Delete p95 (ms) | Delete total (s) |")
    a("|---|---|---|---|---|---|---|---|")
    for n in sorted(runs, key=lambda x: int(x)):
        r = runs[n]
        a("| %s | %s | %s | %s | %s | %s | %s | %s |" % (
            n,
            fmt(g(r, "create", "latency", "p50_ms"), nd=3),
            fmt(g(r, "create", "latency", "p95_ms"), nd=3),
            fmt(g(r, "create", "latency", "max_ms"), nd=3),
            fmt(g(r, "create", "total_seconds")),
            fmt(g(r, "delete", "latency", "p50_ms"), nd=3),
            fmt(g(r, "delete", "latency", "p95_ms"), nd=3),
            fmt(g(r, "delete", "total_seconds")),
        ))
    a("")
    a("### Create latency vs. current graph count")
    a("")
    a("Each bucket groups operations by how many graphs already existed, so a "
      "rising trend is direct evidence of the O(N) copy-on-write cost in "
      "`Galaxy::CreateGraph` (src/db/galaxy.cpp:192-193).")
    a("")
    a("| Graphs (bucket) | n | p50 (ms) | p95 (ms) | max (ms) |")
    a("|---|---|---|---|---|")
    for n in sorted(runs, key=lambda x: int(x)):
        buckets = g(runs[n], "create", "buckets", default={}) or {}
        for b in sorted(buckets, key=lambda s: int(s.split("-")[0])):
            bs = buckets[b]
            # The success path stores a summary dict; the failure path may store
            # the raw list of per-op seconds. Normalise both.
            if isinstance(bs, list):
                bs = _summary_from_seconds(bs)
            if not isinstance(bs, dict) or not bs.get("n"):
                continue
            a("| %s | %s | %s | %s | %s |" % (
                b, bs.get("n"),
                fmt(bs.get("p50_ms"), nd=3), fmt(bs.get("p95_ms"), nd=3),
                fmt(bs.get("max_ms"), nd=3)))
    a("")

    # ---- query ----
    a("## 4. Query latency and throughput")
    a("")
    a("| Graphs | First query, default (ms) | First query, last graph (ms) | Repeated p50 (ms) | Repeated p95 (ms) | Repeated p99 (ms) | Read tps | Write tps | Errors |")
    a("|---|---|---|---|---|---|---|---|---|")
    for n in sorted(runs, key=lambda x: int(x)):
        r = runs[n]
        a("| %s | %s | %s | %s | %s | %s | %s | %s | %s |" % (
            n,
            fmt(g(r, "first_query", "default_seconds", default=0) * 1000
                if g(r, "first_query", "default_seconds") is not None else None, nd=3),
            fmt(g(r, "first_query", "last_graph_seconds", default=0) * 1000
                if g(r, "first_query", "last_graph_seconds") is not None else None, nd=3),
            fmt(g(r, "repeated_query", "latency", "p50_ms"), nd=3),
            fmt(g(r, "repeated_query", "latency", "p95_ms"), nd=3),
            fmt(g(r, "repeated_query", "latency", "p99_ms"), nd=3),
            fmt(g(r, "throughput", "read_tps"), nd=1),
            fmt(g(r, "throughput", "write_tps"), nd=1),
            fmt(g(r, "throughput", "errors")),
        ))
    a("")
    a("Query used: `%s` (read), `%s` (write, unique value per request)." % (
        "MATCH (n) RETURN count(n)", "CREATE (n:phase0bench {v: <counter>})"))
    a("")

    # ---- backup ----
    a("## 5. Snapshot and restore")
    a("")
    a("| Graphs | Snapshot (s) | Snapshot size | Snapshot files | Restore copy (s) | Restore startup (s) | Restore total (s) | Verified | Graphs after restore |")
    a("|---|---|---|---|---|---|---|---|---|")
    for n in sorted(runs, key=lambda x: int(x)):
        r = runs[n]
        a("| %s | %s | %s | %s | %s | %s | %s | %s | %s |" % (
            n,
            fmt(g(r, "snapshot", "seconds")),
            bytes_to_human(g(r, "snapshot", "bytes")),
            fmt(g(r, "snapshot", "files")),
            fmt(g(r, "restore", "copy_seconds")),
            fmt(g(r, "restore", "startup_seconds")),
            fmt(g(r, "restore", "total_seconds")),
            g(r, "restore", "verified", default="-"),
            g(r, "restore", "graphs_found", default="-"),
        ))
    a("")
    a("Snapshot is taken online via `CALL dbms.takeSnapshot()`; it is whole-server "
      "and O(N) (src/db/galaxy.cpp:505-531, src/db/graph_manager.cpp:298-316).")
    a("")

    # ---- failures / limits ----
    a("## 6. Failures and observed limits")
    a("")
    failures = []
    for n in sorted(runs, key=lambda x: int(x)):
        r = runs[n]
        for phase_name, val in sorted(r.items()):
            e = err(val)
            if e:
                failures.append((n, phase_name, e, val.get("peak_observed")))
        if r.get("fatal"):
            failures.append((n, "fatal", r["fatal"], None))
    if not failures:
        a("No phase failures were recorded in this run.")
    else:
        a("| Graphs | Phase | Error | Resource peaks at failure |")
        a("|---|---|---|---|")
        for n, phase_name, e, peaks in failures:
            a("| %s | `%s` | %s | %s |" % (
                n, phase_name, str(e).replace("\n", " ")[:300],
                json.dumps(peaks) if peaks else "-"))
    a("")

    # ---- notable observations ----
    a("## 7. Observations")
    a("")
    a("Automatically derived from this run; confirm against "
      "`docs/architecture/07-scalability-risks.md`.")
    a("")
    obs = []
    ns = sorted(int(x) for x in runs)
    # A create phase that stopped early is the single most important result:
    # it is the measured ceiling, not a flaky failure.
    for n in sorted(runs, key=lambda x: int(x)):
        c = g(runs[n], "create", default={}) or {}
        if c.get("error") and c.get("failed_at_graph_index"):
            obs.append(
                "**Graph creation stopped at %s graphs (target %s).** The "
                "server rejected graph #%s with: `%s`. Resource peaks at that "
                "moment: %s. This is the measured graph ceiling for this build, "
                "not a transient error — see docs/architecture/07-scalability-risks.md R0."
                % (c.get("graphs_present_at_failure"),
                   g(runs[n], "graphs_target", default=c.get("requested")),
                   c.get("failed_at_graph_index"), str(c["error"])[:200],
                   json.dumps(c.get("peak_observed"))))
    if len(ns) >= 2:
        first, last = ns[0], ns[-1]
        s_first = g(runs[str(first)], "startup", "seconds")
        s_last = g(runs[str(last)], "startup", "seconds")
        if s_first and s_last:
            obs.append("Startup grew from %.2fs at %d graph(s) to %.2fs at %d "
                       "graphs (x%.1f)." % (s_first, first, s_last, last, s_last / s_first))
        th_first = g(runs[str(first)], "steady_metrics", "threads")
        th_last = g(runs[str(last)], "steady_metrics", "threads")
        if th_first and th_last:
            obs.append("Thread count grew from %d to %d (+%d) across %d extra "
                       "graphs, consistent with one LMDB validator thread per graph."
                       % (th_first, th_last, th_last - th_first, last - first))
        fd_first = g(runs[str(first)], "steady_metrics", "fds")
        fd_last = g(runs[str(last)], "steady_metrics", "fds")
        if fd_first and fd_last:
            obs.append("File descriptors grew from %d to %d (+%d)."
                       % (fd_first, fd_last, fd_last - fd_first))
        c_first = g(runs[str(first)], "create", "latency", "p50_ms")
        c_last = g(runs[str(last)], "create", "latency", "p50_ms")
        if c_first and c_last:
            obs.append("Median graph-create latency moved from %.3fms to %.3fms; "
                       "see the bucket table for the trend vs. graph count."
                       % (c_first, c_last))
    if not obs:
        obs.append("Not enough successful phases to derive observations.")
    for o in obs:
        a("- %s" % o)
    a("")

    # ---- reproduction ----
    a("## 8. Reproduction")
    a("")
    a("```bash")
    a("# 1. build (see dev/phase0/images.lock for the pinned image)")
    a("dev/phase0/doctor.sh")
    a("dev/phase0/build.sh")
    a("")
    a("# 2. reproduce these measurements")
    a("GRAPH_COUNTS='%s'" % " ".join(str(x) for x in ns))
    a("PHASE0_DOCKER_EXTRA='--cpus=4 --memory=6g' \\")
    a("  dev/phase0/run_bench.sh --graphs $GRAPH_COUNTS \\")
    a("    --out benchmark/scaling/results/baseline.json")
    a("")
    a("# 3. render this report")
    a("python3 benchmark/scaling/report.py \\")
    a("  benchmark/scaling/results/baseline.json")
    a("```")
    a("")
    a("Run inside the pinned arm64 container. Do not compare numbers taken on a "
      "different image or with different CPU/memory limits.")
    a("")
    return "\n".join(out) + "\n"


def main(argv=None):
    ap = argparse.ArgumentParser()
    ap.add_argument("result_json")
    ap.add_argument("-o", "--output", default=None)
    args = ap.parse_args(argv if argv is not None else sys.argv[1:])
    with open(args.result_json) as f:
        doc = json.load(f)
    doc["_source"] = args.result_json
    text = render(doc)
    out = args.output or os.path.join(os.path.dirname(args.result_json) or ".", "BASELINE.md")
    with open(out, "w") as f:
        f.write(text)
    sys.stderr.write("wrote %s\n" % out)
    return 0


if __name__ == "__main__":
    sys.exit(main())
